"""Support classes for shadow and angel aspects."""

class ShadowAgent:
    """Represents an agent's shadow aspect."""

    def guide(self) -> str:
        """Return guidance from the shadow."""
        return "Senca šepeta dvom in strah."


class AngelAgent:
    """Represents an agent's angelic aspect."""

    def guide(self) -> str:
        """Return guidance from the angel."""
        return "Angel vodi k razumevanju in ljubezni."
