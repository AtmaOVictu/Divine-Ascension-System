from __future__ import annotations

"""Ontological agent capable of transitioning philosophical states."""

from dataclasses import dataclass, field
from typing import List

from .symbolic import check_transition


@dataclass
class Agent:
    """Represents an ontological agent."""

    name: str
    state: str = "Ego"
    tension: float = 0.0
    emotion: float = 0.0
    history: List[str] = field(default_factory=lambda: ["Ego"])

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = value
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if check_transition(self.tension, self.emotion):
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def principle(self) -> str:
        """Return the philosophical principle of the current state."""
        if self.state == "Ego":
            return "Resnica je absolutna in neodvisna od drugih."
        if self.state == "Jaz":
            return "Resnica je relativna, oblikovana z našimi odnosi."
        return "Vse resnice so eno, medsebojno povezane."

    def respond(self, question: str) -> str:
        """Return a philosophical response influenced by emotion."""
        base = self.principle()
        if self.emotion > 0.5:
            return f"{base} (odziv z visokimi čustvi)"
        return base
