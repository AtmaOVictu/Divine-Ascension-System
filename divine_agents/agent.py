class Agent:
    """Represents an ontological agent capable of transitioning states.

    The agent maintains an ontological ``state`` (``Ego``, ``Jaz`` or
    ``Enotnost``) together with ``tension`` and ``emotion`` levels.  A
    transition to the next state occurs when either the tension exceeds
    ``0.7`` or the emotion exceeds ``0.5``.
    """

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = value
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    # New helper to generate an emotional prefix for responses
    def _emotion_prefix(self) -> str:
        if self.emotion > 0.7:
            return "Z mocnim custvom povem, da "
        if self.emotion > 0.3:
            return "Custveno verjamem, da "
        return ""

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state and emotion."""
        prefix = self._emotion_prefix()
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."
        return prefix + base
