"""Core classes for the divine agents framework."""

from enum import Enum


class Emotion(Enum):
    """Simple set of emotions influencing dialogue and transitions."""

    NEUTRAL = "neutral"
    JOY = "joy"
    FEAR = "fear"
    ANGER = "anger"


class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0,
                 emotion_type: Emotion = Emotion.NEUTRAL):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = value
        self.tension += value

    def set_emotion(self, emotion: Emotion, intensity: float) -> None:
        """Set emotion type and update intensity."""
        self.emotion_type = emotion
        self.update_emotion(intensity)

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        base = {
            "Ego": "Resnica je absolutna in neodvisna od drugih.",
            "Jaz": "Resnica je relativna, oblikovana z našimi odnosi.",
            "Enotnost": "Vse resnice so eno, medsebojno povezane.",
        }[self.state]
        if self.emotion_type == Emotion.ANGER:
            return f"(jezno) {base}"
        if self.emotion_type == Emotion.FEAR:
            return f"(v strahu) {base}"
        if self.emotion_type == Emotion.JOY:
            return f"(veselo) {base}"
        return base
