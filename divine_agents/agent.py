class Agent:
    """Represent an ontological agent capable of transitioning states.

    State transitions occur when either the ``tension`` or ``emotion`` levels
    exceed predefined thresholds. Each agent keeps a history of visited states
    to make the behaviour easy to inspect during tests.
    """

    STATES = ("Ego", "Jaz", "Enotnost")
    EMOTION_THRESHOLD = 0.5
    TENSION_THRESHOLD = 0.7

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly.

        Parameters
        ----------
        value:
            New emotion intensity. The value is clamped to the ``[0, 1]`` range
            and added to the current tension level. This mirrors how strong
            emotions increase the internal pressure of an agent.
        """
        self.emotion = max(0.0, min(1.0, value))
        self.tension = max(0.0, min(1.0, self.tension + self.emotion))

    def update_tension(self, value: float) -> None:
        """Directly set tension level and clamp it to ``[0, 1]``."""
        self.tension = max(0.0, min(1.0, value))

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > self.TENSION_THRESHOLD or self.emotion > self.EMOTION_THRESHOLD:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state.

        The response subtly changes with the agent's emotional intensity.
        Higher emotion results in more emphasised answers which is used by the
        tests to validate correct behaviour.
        """
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        if self.emotion > self.EMOTION_THRESHOLD:
            return f"{base} (čustvo: {self.emotion:.1f})"
        return base
