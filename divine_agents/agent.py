class Agent:
    """Represent an ontological agent capable of state transitions."""

    STATES = ("Ego", "Jaz", "Enotnost")
    THRESHOLD_TENSION = 0.7
    THRESHOLD_EMOTION = 0.5

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_type: str | None = None) -> None:
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def feel(self, emotion_type: str, intensity: float) -> None:
        """Set the agent's emotion and adjust tension accordingly."""
        self.emotion_type = emotion_type
        self.emotion = intensity
        self.tension = min(1.0, self.tension + intensity)

    def update_tension(self, value: float) -> None:
        """Directly set the tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > self.THRESHOLD_TENSION or self.emotion > self.THRESHOLD_EMOTION:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        emotion_note = ""
        if self.emotion_type == "fear":
            emotion_note = " (z občutkom strahu)"
        elif self.emotion_type == "joy":
            emotion_note = " (z veseljem)"
        elif self.emotion_type == "anger":
            emotion_note = " (z jezo)"

        return f"{base}{emotion_note}"
