class Agent:
    """Ontological agent capable of state transitions based on tension and emotion."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0) -> None:
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.history = [state]

    def update_emotion(self, delta: float) -> None:
        """Adjust emotion level and update tension accordingly."""
        self.emotion = max(0.0, min(1.0, self.emotion + delta))
        self.tension = max(0.0, min(1.0, self.tension + abs(delta)))

    def update_tension(self, value: float) -> None:
        """Directly set the agent's tension level."""
        self.tension = max(0.0, min(1.0, value))

    def transition(self) -> str:
        """Transition to the next state if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer influenced by the current state and emotion."""
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        if self.emotion > 0.5:
            base += " Čutim močna čustva ob tem."  # emotional emphasis
        return base
