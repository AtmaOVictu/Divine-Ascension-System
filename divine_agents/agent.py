class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_label: str = "neutral"):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_label = emotion_label
        self.history = [state]

    def update_emotion(self, label: str, value: float) -> None:
        """Update emotion intensity and type, influencing tension."""
        self.emotion_label = label
        self.emotion = value
        # Emotions influence tension differently
        modifiers = {
            "fear": 0.2,
            "anger": 0.3,
            "joy": -0.1,
            "sorrow": 0.1,
        }
        self.tension += value + modifiers.get(label, 0.0)

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        emotion_prefix = {
            "fear": "V strahu pravim:",
            "anger": "Z jezo povem:",
            "joy": "Z veseljem delim:",
            "sorrow": "Žalostno izrekam:",
        }.get(self.emotion_label, "")

        return f"{emotion_prefix} {base}".strip()
