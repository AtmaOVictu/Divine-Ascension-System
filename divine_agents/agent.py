class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0,
                 emotion_type: str = "neutral"):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def update_emotion(self, intensity: float, emotion_type: str = "neutral") -> None:
        """Update emotion intensity, type and adjust tension accordingly."""
        self.emotion = intensity
        self.emotion_type = emotion_type
        self.tension += intensity

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def section_transition(self) -> str:
        """Fine-grained transition based on tension and emotion thresholds."""
        if self.tension < 0.3:
            self.state = "Ego"
        elif self.emotion > 0.5:
            self.state = "Jaz"
        else:
            self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        prefix = ""
        if self.emotion_type == "fear":
            prefix = "(prestasen) "
        elif self.emotion_type == "anger":
            prefix = "(jezno) "
        elif self.emotion_type == "joy":
            prefix = "(veselo) "

        if self.state == "Ego":
            return prefix + "Resnica je absolutna in neodvisna od drugih."
        if self.state == "Jaz":
            return prefix + "Resnica je relativna, oblikovana z našimi odnosi."
        return prefix + "Vse resnice so eno, medsebojno povezane."
