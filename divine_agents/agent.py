"""Ontological agent model used throughout the system."""

from typing import Dict


EMOTION_IMPACT: Dict[str, float] = {
    "fear": 0.4,
    "joy": 0.3,
    "anger": 0.5,
    "sorrow": 0.3,
    "neutral": 0.0,
}


class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_type: str = "neutral") -> None:
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = value
        self.tension += value

    def apply_emotion(self, emotion: str, intensity: float) -> None:
        """Apply a named emotion and adjust internal tension."""
        self.emotion_type = emotion
        impact = EMOTION_IMPACT.get(emotion, 0.0)
        self.emotion = intensity
        self.tension += intensity + impact

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def philosophical_view(self) -> str:
        """Return the philosophical principle for the current state."""
        if self.state == "Ego":
            return "Resnica je absolutna in neodvisna od drugih."
        if self.state == "Jaz":
            return "Resnica je relativna, oblikovana z našimi odnosi."
        return "Vse resnice so eno, medsebojno povezane."

    def respond(self, question: str) -> str:
        """Return a philosophical answer influenced by emotion."""
        emotion_note = (
            f"[{self.emotion_type}] " if self.emotion_type != "neutral" else ""
        )
        return emotion_note + self.philosophical_view()
