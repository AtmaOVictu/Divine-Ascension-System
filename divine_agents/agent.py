class Agent:
    """Represents an ontological agent capable of transitioning states.

    Agents hold an ontological ``state`` (``Ego``, ``Jaz`` or ``Enotnost``), an
    ``tension`` value and an ``emotion`` intensity.  A textual ``emotion_label``
    can be attached to describe the current emotional feeling.  Transitions are
    triggered when either ``tension`` is greater than ``0.7`` or ``emotion`` is
    greater than ``0.5``.
    """

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_label: str = ""):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_label = emotion_label
        self.history = [state]

    def update_emotion(self, value: float, label: str | None = None) -> None:
        """Update emotion intensity, label and adjust tension.

        Parameters
        ----------
        value: float
            Numeric intensity of the emotion.
        label: str | None
            Optional textual description of the emotion.
        """
        self.emotion = value
        if label is not None:
            self.emotion_label = label
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on state and emotion."""
        emotion_part = (
            f" Občutim {self.emotion_label}." if self.emotion_label else ""
        )
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."
        return base + emotion_part
