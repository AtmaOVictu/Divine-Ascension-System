"""Core agent logic used in philosophical simulations."""

from dataclasses import dataclass, field
from typing import List


@dataclass
class Agent:
    """Represents an ontological agent capable of transitioning states."""

    name: str
    state: str = "Ego"
    tension: float = 0.0
    emotion: float = 0.0
    emotion_type: str = "neutral"
    history: List[str] = field(default_factory=list)

    STATES = ("Ego", "Jaz", "Enotnost")

    def __post_init__(self) -> None:
        self.history.append(self.state)

    def update_emotion(self, value: float, kind: str = "neutral") -> None:
        """Update emotion intensity and set emotional type.

        Parameters
        ----------
        value: float
            Emotional intensity.
        kind: str, optional
            Descriptor of the current emotion (e.g. ``fear`` or ``joy``).
        """
        self.emotion = value
        self.emotion_type = kind
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state.

        The response also reflects the agent's current emotional stance.
        """
        prefix = ""
        if self.emotion_type == "fear":
            prefix = "V strahu odgovarjam: "
        elif self.emotion_type == "joy":
            prefix = "Z veseljem povem: "
        elif self.emotion_type == "anger":
            prefix = "Z jezo izjavljam: "
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."
        return prefix + base
