"""Ontological agents that transition between Ego, Jaz and Enotnost."""

from __future__ import annotations

class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(
        self,
        name: str,
        state: str = "Ego",
        tension: float = 0.0,
        emotion: float = 0.0,
        emotion_name: str | None = None,
    ) -> None:
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_name = emotion_name
        self.history = [state]

    def update_emotion(self, name: str, value: float) -> None:
        """Update emotion intensity, name and adjust tension."""
        self.emotion_name = name
        self.emotion = value
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    # Mapping from state to philosophical principle
    PRINCIPLES = {
        "Ego": "Resnica je absolutna in neodvisna od drugih.",
        "Jaz": "Resnica je relativna, oblikovana z našimi odnosi.",
        "Enotnost": "Vse resnice so eno, medsebojno povezane.",
    }

    def principle(self) -> str:
        """Return philosophical principle for the current state."""
        return self.PRINCIPLES[self.state]

    def respond(self) -> str:
        """Respond with a statement influenced by emotion and state."""
        prefix = f"[{self.emotion_name}] " if self.emotion_name else ""
        return prefix + self.principle()
