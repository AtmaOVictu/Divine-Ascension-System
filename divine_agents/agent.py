from dataclasses import dataclass, field
from typing import List


@dataclass
class Agent:
    """Represents an ontological agent capable of transitioning states."""

    name: str
    state: str = "Ego"
    tension: float = 0.0
    emotion: float = 0.0
    emotion_type: str = "neutral"
    history: List[str] = field(default_factory=lambda: ["Ego"])

    STATES = ("Ego", "Jaz", "Enotnost")

    def update_emotion(self, emotion_type: str, intensity: float) -> None:
        """Update emotion and adjust tension."""
        self.emotion_type = emotion_type
        self.emotion = intensity
        self.tension += intensity

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    # ----------------------- Dialogue Helpers -----------------------
    def philosophical_truth(self) -> str:
        """Return the base philosophical statement for the current state."""
        if self.state == "Ego":
            return "Resnica je absolutna in neodvisna od drugih."
        if self.state == "Jaz":
            return "Resnica je relativna, oblikovana z našimi odnosi."
        return "Vse resnice so eno, medsebojno povezane."

    def respond(self) -> str:
        """Return a philosophical response influenced by emotion."""
        base = self.philosophical_truth()
        if self.emotion_type == "fear":
            return f"{base} Čutim strah ob tvoji trditvi."
        if self.emotion_type == "anger":
            return f"{base} Jezen sem in iščem odgovor."
        if self.emotion_type == "joy":
            return f"{base} Veseli me naše spoznanje."
        return base
