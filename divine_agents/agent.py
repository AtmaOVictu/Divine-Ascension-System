"""Ontological agents capable of philosophical state transitions."""

from __future__ import annotations


class Agent:
    """Represents an ontological agent with emotional dynamics."""

    STATES = ("Ego", "Jaz", "Enotnost")
    TRANSITION_TENSION = 0.7
    TRANSITION_EMOTION = 0.5
    PHILOSOPHY = {
        "Ego": "Resnica je absolutna in neodvisna od drugih.",
        "Jaz": "Resnica je relativna, oblikovana z našimi odnosi.",
        "Enotnost": "Vse resnice so eno, medsebojno povezane.",
    }

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion and increase tension proportionally."""
        self.emotion = value
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > self.TRANSITION_TENSION or self.emotion > self.TRANSITION_EMOTION:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        base = self.PHILOSOPHY.get(self.state, "")
        if self.emotion > 0.7:
            return f"{base} Čutim to zelo močno!"
        if self.emotion < 0.3:
            return f"{base} Mirno razmišljam."
        return base

