class Agent:
    """Ontological agent with emotional state and tension.

    Agents begin in one of three states: ``Ego``, ``Jaz`` or ``Enotnost``.
    They transition when their ``tension`` exceeds ``0.7`` or their
    ``emotion`` exceeds ``0.5``. Emotional updates also increase tension,
    allowing conversations to naturally evolve towards higher states.
    """

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0, emotion: float = 0.0):
        """Create a new agent.

        Parameters
        ----------
        name:
            Unique identifier for the agent.
        state:
            Initial ontological state. Defaults to ``"Ego"``.
        tension:
            Baseline tension level.
        emotion:
            Current emotional intensity influencing transitions.
        """
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.history = [state]

    def update_emotion(self, value: float) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = value
        # Emotions feed into tension, creating the possibility of transition
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform a state transition when thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer influenced by the current state.

        Emotional intensity colors the response with enthusiasm when above 0.5.
        """
        base: str
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        if self.emotion > 0.5:
            base += "!"
        return base
