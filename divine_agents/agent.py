class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_type: str = "neutral") -> None:
        """Create a new agent.

        Parameters
        ----------
        name:
            Unique identifier for the agent.
        state:
            Ontological state of the agent. One of :data:`STATES`.
        tension:
            Current tension level influencing transitions.
        emotion:
            Intensity of the current emotion.
        emotion_type:
            Descriptive label for the emotion (e.g. ``"fear"`` or ``"joy"``).
        """

        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def update_emotion(self, value: float, emotion_type: str | None = None) -> None:
        """Update emotion intensity and adjust tension accordingly.

        Parameters
        ----------
        value:
            New intensity of emotion.
        emotion_type:
            Optional new emotion descriptor.
        """

        self.emotion = value
        if emotion_type is not None:
            self.emotion_type = emotion_type
        self.tension += value

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer influenced by ontological and emotional state."""
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        prefix = {
            "fear": "Z zaskrbljenostjo",
            "joy": "Z veseljem",
            "anger": "Z jezo",
        }.get(self.emotion_type, "Mirno")

        return f"{prefix} odgovarjam: {base}"
