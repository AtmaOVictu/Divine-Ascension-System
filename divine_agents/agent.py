class Agent:
    """Represents an ontological agent capable of transitioning states.

    The agent tracks its ontological ``state`` (``Ego`` -> ``Jaz`` -> ``Enotnost``),
    emotional intensity and type, and accumulated ``tension``.  State transitions
    occur when ``tension`` exceeds ``0.7`` or ``emotion`` exceeds ``0.5``.
    """

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(
        self,
        name: str,
        state: str = "Ego",
        tension: float = 0.0,
        emotion: float = 0.0,
        emotion_type: str = "neutral",
    ):
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type
        self.history = [state]

    def update_emotion(self, intensity: float, emotion_type: str) -> None:
        """Update emotion intensity and adjust tension accordingly."""
        self.emotion = intensity
        self.emotion_type = emotion_type
        self.tension += intensity

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state.

        The answer also includes the agent's current emotional tone.
        """
        if self.state == "Ego":
            base = "Resnica je absolutna in neodvisna od drugih."
        elif self.state == "Jaz":
            base = "Resnica je relativna, oblikovana z našimi odnosi."
        else:
            base = "Vse resnice so eno, medsebojno povezane."

        if self.emotion_type and self.emotion_type != "neutral":
            return f"({self.emotion_type}) {base}"
        return base
