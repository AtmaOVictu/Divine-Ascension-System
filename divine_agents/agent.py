"""Base ontology agent module."""


class Agent:
    """Represents an ontological agent capable of transitioning states."""

    STATES = ("Ego", "Jaz", "Enotnost")

    def __init__(self, name: str, state: str = "Ego", tension: float = 0.0,
                 emotion: float = 0.0, emotion_type: str | None = None) -> None:
        self.name = name
        self.state = state
        self.tension = tension
        self.emotion = emotion
        self.emotion_type = emotion_type or "neutral"
        self.history = [state]

    def update_emotion(self, value: float, emotion_type: str | None = None) -> None:
        """Update emotion intensity and adjust tension accordingly.

        Parameters
        ----------
        value:
            Intensity of the emotion.
        emotion_type:
            Type of emotion influencing the agent (e.g. ``fear`` or ``joy``).
        """

        self.emotion = value
        if emotion_type is not None:
            self.emotion_type = emotion_type

        if self.emotion_type in {"fear", "anger"}:
            self.tension += value
        elif self.emotion_type == "joy":
            self.tension = max(0.0, self.tension - value * 0.5)
        else:
            self.tension += value * 0.5

    def update_tension(self, value: float) -> None:
        """Directly set tension level."""
        self.tension = value

    def transition(self) -> str:
        """Perform state transition if thresholds are exceeded."""
        if self.tension > 0.7 or self.emotion > 0.5:
            if self.state == "Ego":
                self.state = "Jaz"
            elif self.state == "Jaz":
                self.state = "Enotnost"
        self.history.append(self.state)
        return self.state

    def respond(self, question: str) -> str:
        """Return a philosophical answer depending on the current state."""
        base = {
            "Ego": "Resnica je absolutna in neodvisna od drugih.",
            "Jaz": "Resnica je relativna, oblikovana z našimi odnosi.",
            "Enotnost": "Vse resnice so eno, medsebojno povezane.",
        }[self.state]

        if self.emotion_type in {"fear", "anger"}:
            mood = "vznemirjeno"
        elif self.emotion_type == "joy":
            mood = "radostno"
        else:
            mood = "mirno"

        return f"({mood}) {base}"
